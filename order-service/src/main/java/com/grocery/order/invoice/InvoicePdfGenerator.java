package com.grocery.order.invoice;

import com.grocery.order.dto.response.InvoiceFile;
import com.grocery.order.entity.DeliveryAddress;
import com.grocery.order.entity.Order;
import com.grocery.order.entity.OrderAmounts;
import com.grocery.order.entity.OrderItem;
import com.grocery.order.entity.StoreDetails;
import com.grocery.order.enums.PaymentMethod;
import com.grocery.order.exception.BusinessException;
import com.grocery.order.logging.Loggable;
import com.lowagie.text.Document;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;

/**
 * Builds the tax invoice of an order as a PDF, with OpenPDF.
 *
 * Prices on the platform INCLUDE tax (GST), so the invoice shows how much of every line is tax:
 * tax = line total x tax% / (100 + tax%). Example: 56.00 at 12 % contains 6.00 tax.
 * Everything comes from the order's own copies (store, address, items, amounts), so an invoice never changes later.
 */
@Component
@Loggable   // Renders PDFs: LoggingAspect logs the time of every call and warns when it is slow
public class InvoicePdfGenerator {

    private static final ZoneId INDIA = ZoneId.of("Asia/Kolkata");
    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd MMM yyyy, HH:mm");
    private static final Font TITLE = new Font(Font.HELVETICA, 18, Font.BOLD);
    private static final Font BOLD = new Font(Font.HELVETICA, 10, Font.BOLD);
    private static final Font NORMAL = new Font(Font.HELVETICA, 10);
    private static final Font SMALL = new Font(Font.HELVETICA, 8, Font.NORMAL, Color.GRAY);
    private static final Color HEADER_BACKGROUND = new Color(235, 242, 235);

    /** Invoices exist once the store accepted the order, and not for a cancelled one: otherwise a 400 answer. */
    public void checkHasInvoice(Order order) {
        if (!order.hasInvoice()) {
            throw new BusinessException("Order %d has no invoice (it is %s). Invoices exist once the store accepted the order."
                    .formatted(order.getId(), order.getStatus()));
        }
    }

    public InvoiceFile generate(Order order) {
        checkHasInvoice(order);
        ByteArrayOutputStream pdf = new ByteArrayOutputStream();
        Document document = new Document(PageSize.A4, 40, 40, 40, 40);
        PdfWriter.getInstance(document, pdf);
        document.open();

        document.add(new Paragraph("TAX INVOICE", TITLE));
        document.add(new Paragraph("Invoice %s   |   Order #%d   |   %s".formatted(
                order.getInvoiceNumber(), order.getId(), DATE.format(order.getCreatedAt().atZone(INDIA))), NORMAL));
        document.add(new Paragraph(" "));
        document.add(parties(order.getStore(), order.getDeliveryAddress()));
        document.add(new Paragraph(" "));
        document.add(items(order));
        document.add(totals(order.getAmounts()));
        document.add(new Paragraph(" "));
        document.add(new Paragraph(paymentLine(order), NORMAL));
        document.add(new Paragraph("All prices include GST. Amounts in INR. This invoice was generated by the Grocery platform.", SMALL));

        document.close();
        return InvoiceFile.of(order.getInvoiceNumber(), pdf.toByteArray());
    }

    /** Seller on the left, customer on the right. */
    private PdfPTable parties(StoreDetails store, DeliveryAddress address) {
        PdfPTable table = new PdfPTable(2);
        table.setWidthPercentage(100);
        table.addCell(block("Sold by", store.getName(), store.getAddress(), "Phone " + store.getPhone()));
        table.addCell(block("Deliver to", address.getContactName(), address.oneLine(), "Phone " + address.getContactPhone()));
        return table;
    }

    private PdfPTable items(Order order) {
        PdfPTable table = new PdfPTable(new float[]{5, 1.2f, 2, 1.3f, 1.8f, 2});
        table.setWidthPercentage(100);
        for (String heading : new String[]{"Item", "Qty", "Unit price", "GST %", "GST", "Amount"}) {
            PdfPCell cell = cell(heading, BOLD, Element.ALIGN_LEFT);
            cell.setBackgroundColor(HEADER_BACKGROUND);
            table.addCell(cell);
        }
        for (OrderItem item : order.getItems()) {
            table.addCell(cell(item.getProductName() + " (" + item.getUnitQuantity().stripTrailingZeros().toPlainString()
                    + " " + item.getUnit() + ")", NORMAL, Element.ALIGN_LEFT));
            table.addCell(cell(String.valueOf(item.getQuantity()), NORMAL, Element.ALIGN_RIGHT));
            table.addCell(cell(money(item.getUnitPrice()), NORMAL, Element.ALIGN_RIGHT));
            table.addCell(cell(item.getTaxPercentage().stripTrailingZeros().toPlainString(), NORMAL, Element.ALIGN_RIGHT));
            table.addCell(cell(money(taxIncludedIn(item.getLineTotal(), item.getTaxPercentage())), NORMAL, Element.ALIGN_RIGHT));
            table.addCell(cell(money(item.getLineTotal()), NORMAL, Element.ALIGN_RIGHT));
        }
        return table;
    }

    private PdfPTable totals(OrderAmounts amounts) {
        PdfPTable table = new PdfPTable(new float[]{11.3f, 2});
        table.setWidthPercentage(100);
        totalRow(table, "Items total", money(amounts.getItemsTotal()), NORMAL);
        if (amounts.getCouponDiscount().signum() > 0) {
            totalRow(table, "Coupon " + amounts.getCouponCode(), "- " + money(amounts.getCouponDiscount()), NORMAL);
        }
        totalRow(table, "Delivery fee", money(amounts.getDeliveryFee()), NORMAL);
        totalRow(table, "Total", money(amounts.getTotalAmount()), BOLD);
        totalRow(table, "of which GST", money(amounts.getTaxIncluded()), SMALL);
        return table;
    }

    /**
     * "Payment: paid online (payment #42)", "Payment: cash on delivery, paid (payment #43)" or
     * "Payment: cash on delivery, to be paid on delivery (payment #43)". Older orders have no payment number.
     */
    static String paymentLine(Order order) {
        String how;
        if (order.getPaymentMethod() == PaymentMethod.COD) {
            how = order.isPaid() ? "cash on delivery, paid" : "cash on delivery, to be paid on delivery";
        } else {
            how = order.isPaid() ? "paid online" : "online, " + order.getPaymentStatus();   // online orders are paid before the store accepts
        }
        return order.getPaymentId() == null ? "Payment: " + how : "Payment: %s (payment #%d)".formatted(how, order.getPaymentId());
    }

    /** 56.00 incl. 12 % -> 6.00 */
    static BigDecimal taxIncludedIn(BigDecimal amount, BigDecimal taxPercentage) {
        return amount.multiply(taxPercentage).divide(BigDecimal.valueOf(100).add(taxPercentage), 2, RoundingMode.HALF_UP);
    }

    private PdfPCell block(String title, String... lines) {
        PdfPCell cell = new PdfPCell();
        cell.setPadding(6);
        cell.addElement(new Paragraph(title, BOLD));
        for (String line : lines) {
            cell.addElement(new Paragraph(line, NORMAL));
        }
        return cell;
    }

    private PdfPCell cell(String text, Font font, int alignment) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setPadding(5);
        cell.setHorizontalAlignment(alignment);
        return cell;
    }

    private void totalRow(PdfPTable table, String label, String value, Font font) {
        PdfPCell labelCell = cell(label, font, Element.ALIGN_RIGHT);
        PdfPCell valueCell = cell(value, font, Element.ALIGN_RIGHT);
        labelCell.setBorder(Rectangle.NO_BORDER);
        valueCell.setBorder(Rectangle.NO_BORDER);
        table.addCell(labelCell);
        table.addCell(valueCell);
    }

    private String money(BigDecimal amount) {
        return amount.setScale(2, RoundingMode.HALF_UP).toPlainString();
    }
}
